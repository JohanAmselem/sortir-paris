import { pgTable, uuid, text, boolean, timestamp, index, primaryKey } from 'drizzle-orm/pg-core'
import { sql } from 'drizzle-orm'
import { users } from './users'
import { events } from './events'

/**
 * Artist alerts. Managed in packages/db/sql/0010_artist_alerts.sql.
 * artist_key: lowercase, accents folded, non-alphanumeric → space, collapsed
 * (same rule in scrapers/utils/artists.py and apps/web/src/lib/artists.ts).
 */

/** Who plays in an event (filled by the scrapers). */
export const eventArtists = pgTable(
  'event_artists',
  {
    eventId: uuid('event_id')
      .references(() => events.id, { onDelete: 'cascade' })
      .notNull(),
    artistKey: text('artist_key').notNull(),
    name: text('name').notNull(),
    /** 'source': given by the source (reliable); 'title': parsed from the title. */
    origin: text('origin', { enum: ['source', 'title'] }).default('title').notNull(),
  },
  (table) => [primaryKey({ columns: [table.eventId, table.artistKey] }), index('idx_event_artists_key').on(table.artistKey)]
)

/** Alert preferences, one row per member (created on first change or first e-mail). */
export const alertSettings = pgTable('alert_settings', {
  userId: uuid('user_id')
    .primaryKey()
    .references(() => users.id, { onDelete: 'cascade' }),
  emailEnabled: boolean('email_enabled').default(true).notNull(),
  pushEnabled: boolean('push_enabled').default(false).notNull(),
  notifyNewDate: boolean('notify_new_date').default(true).notNull(),
  notifyOnSale: boolean('notify_on_sale').default(true).notNull(),
  notifyReminder: boolean('notify_reminder').default(true).notNull(),
  /** Unsubscribe link without login. Default generated by the database (never set it from the app). */
  unsubscribeToken: text('unsubscribe_token')
    .unique()
    .notNull()
    .default(sql`(replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', ''))`),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
})

/** Web Push subscriptions, one per browser / device. */
export const pushSubscriptions = pgTable(
  'push_subscriptions',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .references(() => users.id, { onDelete: 'cascade' })
      .notNull(),
    endpoint: text('endpoint').unique().notNull(),
    p256dh: text('p256dh').notNull(),
    auth: text('auth').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    lastErrorAt: timestamp('last_error_at', { withTimezone: true }),
  },
  (table) => [index('idx_push_subscriptions_user').on(table.userId)]
)

export type AlertKind = 'new_date' | 'on_sale' | 'reminder'

/** Alert log: never twice the same (member, event, kind). */
export const alertDeliveries = pgTable(
  'alert_deliveries',
  {
    userId: uuid('user_id')
      .references(() => users.id, { onDelete: 'cascade' })
      .notNull(),
    eventId: uuid('event_id')
      .references(() => events.id, { onDelete: 'cascade' })
      .notNull(),
    kind: text('kind', { enum: ['new_date', 'on_sale', 'reminder'] }).notNull(),
    channels: text('channels').array().default([]).notNull(),
    sentAt: timestamp('sent_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (table) => [primaryKey({ columns: [table.userId, table.eventId, table.kind] }), index('idx_alert_deliveries_sent').on(table.sentAt)]
)
